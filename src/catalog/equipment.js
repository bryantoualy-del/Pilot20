export const WEAPONS = Object.fromEntries(
  weapons.map(
    ([
      id,
      fr,
      en,
      dice,
      damageType,
      category,
      ranged,
      finesse,
      proficiency,
    ]) => [
      id,
      {
        name: { fr, en },
        dice,
        damageType,
        category,
        ranged,
        finesse,
        proficiency,
      },
    ],
  ),
);
export function weaponProfile(id, scores, proficiencies) {
  const w = WEAPONS[id];
  if (!w || !w.dice) return null;
  return {
    ability: w.finesse
      ? scores.dex > scores.str
        ? "dex"
        : "str"
      : w.ranged
        ? "dex"
        : "str",
    ranged:w.ranged,
    proficient:
      proficiencies.includes(w.proficiency) ||
      proficiencies.includes(w.category + "-weapons"),
    bonus: 0,
    dice: w.dice,
    damageType: w.damageType,
  };
}

